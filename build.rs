//! Build script.
//!
//! Cluster secrets are no longer compiled into the binary: every installation
//! generates a random one on first start and writes it to its own config file.
//! This script only derives a non-secret build fingerprint so that server and
//! agent logs can tell whether they came from the same build.

use sha2::{Digest, Sha256};
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    // Optional CI value used to distinguish two builds of the same version.
    // It is not a cluster secret and is safe to print in logs.
    println!("cargo:rerun-if-env-changed=PROMPTSYNC_BUILD_ID");

    let version = env::var("CARGO_PKG_VERSION").unwrap_or_default();
    let target = env::var("TARGET").unwrap_or_default();
    let profile = env::var("PROFILE").unwrap_or_default();
    let build_id = env::var("PROMPTSYNC_BUILD_ID").unwrap_or_default();

    let mut hasher = Sha256::new();
    hasher.update(b"promptsync-build-fingerprint-v2");
    for part in [
        version.as_str(),
        target.as_str(),
        profile.as_str(),
        build_id.as_str(),
    ] {
        // Length-prefix every component so concatenations cannot collide.
        hasher.update((part.len() as u64).to_be_bytes());
        hasher.update(part.as_bytes());
    }
    let digest = hasher.finalize();
    let hex: String = digest.iter().map(|byte| format!("{byte:02x}")).collect();
    let fingerprint = &hex[..12];

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let generated = format!(
        "// @generated by build.rs - never commit this file\n\
         pub const BUILD_FINGERPRINT: &str = \"{fingerprint}\";\n",
    );
    fs::write(out.join("built_secrets.rs"), generated).expect("write generated build info");

    println!("cargo:warning=promptsync build fingerprint {fingerprint}");
}
