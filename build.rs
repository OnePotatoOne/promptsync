//! Build script.
//!
//! Every build embeds **freshly generated random secrets** unless the build is
//! explicitly given a secret through the environment (CI does this so that all
//! release artefacts of one workflow run can talk to each other).
//!
//! Nothing secret is ever written into the repository: generated values go to
//! `$OUT_DIR`, and the optional local secret files live in `secrets/`, which is
//! git-ignored.

use rand::rngs::OsRng;
use rand::RngCore;
use sha2::{Digest, Sha256};
use std::env;
use std::fs;
use std::path::PathBuf;

fn hex32(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=templates/config.toml");
    // Only track the local secrets directory when it exists; a missing path
    // would force a rebuild (and a new random key) on every invocation.
    let secrets_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR")).join("secrets");
    if secrets_dir.exists() {
        println!("cargo:rerun-if-changed=secrets");
    }
    for var in ["PROMPTSYNC_BUILD_SECRET", "PROMPTSYNC_CLUSTER_SECRET"] {
        println!("cargo:rerun-if-env-changed={var}");
    }

    let secret = resolve_secret();

    // Build fingerprint: non-secret identifier so that server and agent logs can
    // tell whether they were produced by the same build.
    let mut hasher = Sha256::new();
    hasher.update(b"promptsync-build-fingerprint-v1");
    hasher.update(secret.as_bytes());
    let fingerprint = hex32(&hasher.finalize())[..12].to_string();

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let generated = format!(
        "// @generated by build.rs - never commit this file\n\
         pub const EMBEDDED_CLUSTER_SECRET_HEX: &str = \"{secret}\";\n\
         pub const BUILD_FINGERPRINT: &str = \"{fingerprint}\";\n",
    );
    fs::write(out.join("built_secrets.rs"), generated).expect("write generated secrets");

    println!(
        "cargo:warning=promptsync build fingerprint {fingerprint} (random secrets embedded: {})",
        secret_source()
    );
}

fn secret_source() -> &'static str {
    if env_secret().is_some() {
        "from environment"
    } else if file_secret().is_some() {
        "from secrets/cluster_secret.hex"
    } else {
        "generated for this build"
    }
}

fn env_secret() -> Option<String> {
    for var in ["PROMPTSYNC_BUILD_SECRET", "PROMPTSYNC_CLUSTER_SECRET"] {
        if let Ok(value) = env::var(var) {
            let cleaned: String = value
                .trim()
                .chars()
                .filter(|c| c.is_ascii_hexdigit())
                .collect();
            if cleaned.len() == 64 {
                return Some(cleaned.to_ascii_lowercase());
            }
            if !cleaned.is_empty() {
                panic!("{var} must be 64 hex characters (32 bytes)");
            }
        }
    }
    None
}

fn file_secret() -> Option<String> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    read_trimmed(&manifest.join("secrets/cluster_secret.hex")).filter(|s| s.len() == 64)
}

fn resolve_secret() -> String {
    if let Some(secret) = env_secret() {
        return secret;
    }
    if let Some(secret) = file_secret() {
        return secret;
    }
    // Per-build random secret: the server and the agent binaries produced by the
    // same `cargo build` share it, different builds do not.
    let mut bytes = [0u8; 32];
    OsRng.fill_bytes(&mut bytes);
    hex32(&bytes)
}

fn read_trimmed(path: &std::path::Path) -> Option<String> {
    let text = fs::read_to_string(path).ok()?;
    let trimmed = text.trim();
    if trimmed.is_empty() {
        None
    } else {
        Some(trimmed.to_string())
    }
}
